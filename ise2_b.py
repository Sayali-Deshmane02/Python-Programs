import numpy as np
arr1=np.array([1,2])
arr2=np.array([3,4])
print("Addition:",np.array(arr1+arr2))
print("Subtraction :",np.array(arr1-arr2))
print("Product is:",np.array(arr1*arr2))
print("Division is:",np.array(arr1/arr2))
print("Floor division is:",np.array(arr1//arr2))
print("Modulus:",np.array(arr1%arr2))
